import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.model_selection import train_test_split
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import(
    confusion_matrix,
    classification_report,
    precision_score,
    recall_score,
    f1_score,
    roc_auc_score,
    ConfusionMatrixDisplay,
    RocCurveDisplay
)

df=pd.read_csv("/content/creditcard.csv")
print("Dataset loaded successfully!")
print("Dataset shape:",df.shape)
print(df.head())
df.info()
df.isnull().sum()

print("Catagories:",df["Class"].unique())
print("\nCategory counts:")
print(df["Class"].value_counts())
print("\nCategory percentages:")
print(df["Class"].value_counts(normalize=True)*100)

X=df.drop("Class",axis=1)
y=df["Class"]
print("Feature shape:",X.shape)
print("Target shape:",y.shape)
print("\nFeatures:")
print(X.columns.tolist())

df_clean = df.dropna()
X_clean = df_clean.drop("Class", axis=1)
y_clean = df_clean["Class"]
X_train, X_test, y_train, y_test = train_test_split(
    X_clean,
    y_clean,
    test_size=0.20,
    random_state=42,
    stratify=y_clean
)
print("Training data:", X_train.shape)
print("Testing data:", X_test.shape)

model = RandomForestClassifier(
    n_estimators=100,
    class_weight="balanced_subsample",
    random_state=42,
    n_jobs=-1
)
print("Training Random FOrest model...")
model.fit(X_train,y_train)
print("Model training completed successfully!")

y_pred=model.predict(X_test)
y_prob=model.predict_proba(X_test)[:,1]
print("Actual labels:")
print(y_test.head(20))
print(("Predicted labels:"))
print(y_pred[:20])

cm = confusion_matrix(y_test, y_pred, labels=[0, 1])

print("Confusion Matrix:")
print(cm)

ConfusionMatrixDisplay(
    confusion_matrix=cm,
    display_labels=["Genuine", "Fraud"]
).plot(cmap="Blues", values_format="d")

plt.title("Random Forest - Confusion Matrix")
plt.show()

precision = precision_score(
    y_test, y_pred, zero_division=0
)
recall = recall_score(
    y_test, y_pred, zero_division=0
)
f1 = f1_score(
    y_test, y_pred, zero_division=0
)
roc_auc = roc_auc_score(y_test, y_prob)
print(f"Precision : {precision:.4f}")
print(f"Recall    : {recall:.4f}")
print(f"F1-score  : {f1:.4f}")
print(f"ROC-AUC   : {roc_auc:.4f}")
print("\nDetailed Classification Report:")
print(
    classification_report(
        y_test,
        y_pred,
        target_names=["Genuine", "Fraud"],
        zero_division=0
    )
)

results = X_test.copy()
results["Actual"] = y_test
results["Predicted"] = y_pred
results["Fraud_Probability"] = y_prob

actual_fraud = results[results["Actual"] == 1]

print("Total actual fraud cases:", len(actual_fraud))
print(actual_fraud[["Time", "Amount", "Actual", "Predicted", "Fraud_Probability"]].head(20))

print("Fraud detected:", len(results[(results["Actual"] == 1) & (results["Predicted"] == 1)]))
print("Fraud missed:", len(results[(results["Actual"] == 1) & (results["Predicted"] == 0)]))

actual_fraud.to_csv("actual_fraudulent_test_transactions.csv", index=True)
print("File saved successfully!")

importance = pd.Series(model.feature_importances_, index=X.columns)

top10 = importance.nlargest(10)
print("Top 10 Important Features:")
print(top10)

top10.sort_values().plot(kind="barh")
plt.title("Top 10 Important Features")
plt.show()

RocCurveDisplay.from_predictions(
    y_test,
    y_prob,
    name="Random Forest"
)
plt.title("ROC Curve - Credit Card Fraud Detection")
plt.plot([0, 1], [0, 1], "k--")
plt.show()